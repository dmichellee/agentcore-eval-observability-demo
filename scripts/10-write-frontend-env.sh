#!/bin/bash
# ============================================================
# 배포된 리소스 값을 읽어 frontend/.env.local 생성 (git에 올리지 않음)
# 06/06b/07 스크립트 실행 후 사용. 여러 번 실행해도 같은 결과.
# ============================================================
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
source "${SCRIPT_DIR}/config.sh"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
OUT="${PROJECT_ROOT}/frontend/.env.local"

USER_POOL_ID=$(aws cognito-idp list-user-pools --max-results 50 --region "${AWS_REGION}" \
  --query "UserPools[?Name=='${COGNITO_USER_POOL_NAME}'].Id | [0]" --output text --no-cli-pager)
APP_CLIENT_ID=$(aws cognito-idp list-user-pool-clients --user-pool-id "${USER_POOL_ID}" --region "${AWS_REGION}" \
  --query "UserPoolClients[?ClientName=='${PROJECT_PREFIX}-web-client-${ENV}'].ClientId | [0]" --output text --no-cli-pager)
IDENTITY_POOL_ID=$(aws cognito-identity list-identity-pools --max-results 60 --region "${AWS_REGION}" \
  --query "IdentityPools[?IdentityPoolName=='${PROJECT_PREFIX}-identity-${ENV}'].IdentityPoolId | [0]" --output text --no-cli-pager)
RUNTIME_ARN=$(aws bedrock-agentcore-control list-agent-runtimes --region "${AWS_REGION}" \
  --query "agentRuntimes[?agentRuntimeName=='${AGENT_RUNTIME_NAME:-VroomDash_VroomDash}'].agentRuntimeArn | [0]" --output text --no-cli-pager)
DEMO_SECRET=$(aws secretsmanager get-secret-value --secret-id "${PROJECT_PREFIX}/demo-user-${ENV}" \
  --query SecretString --output text --region "${AWS_REGION}" --no-cli-pager)

for v in USER_POOL_ID APP_CLIENT_ID IDENTITY_POOL_ID RUNTIME_ARN; do
  if [ -z "${!v}" ] || [ "${!v}" = "None" ]; then
    echo "ERROR: ${v} not found. Run 06-setup-cognito.sh, 06b-setup-identity-pool.sh and 07-setup-agentcore.sh first." >&2
    exit 1
  fi
done

python3 - "${OUT}" "${DEMO_SECRET}" <<PY
import json, sys
out, secret = sys.argv[1], json.loads(sys.argv[2])
lines = {
    "REACT_APP_REGION": "${AWS_REGION}",
    "REACT_APP_USER_POOL_ID": "${USER_POOL_ID}",
    "REACT_APP_APP_CLIENT_ID": "${APP_CLIENT_ID}",
    "REACT_APP_IDENTITY_POOL_ID": "${IDENTITY_POOL_ID}",
    "REACT_APP_AGENTCORE_RUNTIME_ARN": "${RUNTIME_ARN}",
    "REACT_APP_DEMO_USERNAME": secret["username"],
    "REACT_APP_DEMO_PASSWORD": secret["password"],
}
with open(out, "w") as f:
    f.write("# Generated by scripts/10-write-frontend-env.sh. Do not commit.\n")
    f.writelines(f"{k}={v}\n" for k, v in lines.items())
PY
chmod 600 "${OUT}"
echo "Wrote ${OUT}. For local demos only: the dev server embeds these values in the page."
